#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const serverDir = path.join(root, 'server');
const outputDir = path.join(root, '.gas-build');
const codePath = path.join(root, 'Code.gs');
const bridgePath = path.join(serverDir, 'Bridge.html');

function fail(message) {
  console.error(message);
  process.exit(1);
}

if (!fs.existsSync(codePath) || !fs.existsSync(bridgePath)) fail('Missing Apps Script source or bridge template.');

const pagesOrigin = process.env.PAGES_ORIGIN ||
  'https://' + String(process.env.GITHUB_REPOSITORY || 'AARDMC/AAPHREML-IRERC').split('/')[0].toLowerCase() + '.github.io';
let bridge = fs.readFileSync(bridgePath, 'utf8');
const codeSource = fs.readFileSync(codePath, 'utf8');
const publicFunctions = Array.from(codeSource.matchAll(/function\s+(api[A-Z0-9]\w*)\s*\(/g))
  .map(function(match) { return match[1]; })
  .filter(function(name) { return name !== 'apiInitDatabase'; });
if (!publicFunctions.length) fail('No public RPC functions were found in Code.gs.');

bridge = bridge.replace('__IRERC_PAGES_ORIGIN__', JSON.stringify(pagesOrigin));
bridge = bridge.replace('__IRERC_API_FUNCTIONS__', JSON.stringify(publicFunctions));
if (bridge.indexOf('__IRERC_') !== -1) fail('Bridge template has unresolved build placeholders.');

const names = fs.readdirSync(serverDir).filter(function(name) { return name.endsWith('.gs'); });
const priorities = ['Config.gs', 'Assets.gs'];
const orderedServerFiles = priorities.filter(function(name) { return names.includes(name); })
  .concat(names.filter(function(name) { return priorities.indexOf(name) === -1; }).sort());
const sourceFiles = [
  'Code.gs',
  ...orderedServerFiles.map(function(name) { return path.join('server', name); })
];
const generated = [
  '// Generated by scripts/build-gas.js. Edit the modular sources in GitHub.',
  'var BRIDGE_HTML_ = ' + JSON.stringify(bridge) + ';',
  sourceFiles.map(function(relativePath) {
    return '\n// ---- ' + relativePath + ' ----\n' + fs.readFileSync(path.join(root, relativePath), 'utf8');
  }).join('\n')
].join('\n');

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(path.join(outputDir, 'Code.gs'), generated, 'utf8');
fs.copyFileSync(path.join(root, 'appsscript.json'), path.join(outputDir, 'appsscript.json'));
fs.writeFileSync(path.join(outputDir, '.claspignore'), '**/*\n!Code.gs\n!appsscript.json\n', 'utf8');
console.log('Built .gas-build with Code.gs and appsscript.json only.');
